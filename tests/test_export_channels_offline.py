#!/usr/bin/env python3
"""[HUB-EXPORT-DROPS-FIVE-RUN-FLAGS] — ОТРИЦАТЕЛЬНАЯ половина контракта об экспорте.

ПАРА, А НЕ ДУБЛЬ. Положительную половину — «выбор человека стал виден в экспорте» — держит
разностный гейт `scripts/hub-dom-check.mjs` («каждое поле формы прогона доезжает до экспорта»):
он трогает контрол на НАСТОЯЩЕЙ странице и смотрит, сдвинулся ли отрисованный документ. Такое
утверждение нельзя удовлетворить посторонней строкой, и оно не повторяет формулу `renderBuild`.

Но у него есть ровно одна слепая зона, и она ЗАМЕРЕНА, а не предположена: ему всё равно, КАКИМ
каналом поле уехало. Достаточно дописать пять ключей в YAML-блок вместо флагов в команду — каждое
поле начнёт двигать экспорт, разностный гейт станет ЗЕЛЁНЫМ, а `load_run_config` эти ключи МОЛЧА
выбросит (`_ALLOWED`, `brain/runconfig.py`: неизвестные ключи игнорируются намеренно,
forward-compat). Человек прочитал бы в файле `ci: true` и получил прогон без CI — экспорт лгал бы
ГРОМЧЕ, чем когда молчал. Это дословно ADR-133, только под зелёной проверкой.

Поэтому здесь утверждение ОТРИЦАТЕЛЬНОЕ: ключа, которого загрузчик не читает, в экспортируемом
`run.yaml` быть не может. Отрицательное утверждение посторонней строкой не удовлетворяется, лишних
имён не порождает и исполняется без браузера — а именно браузера у офлайнового сьюта и нет.

ПОЧЕМУ ЗДЕСЬ ДОПУСТИМО СМОТРЕТЬ НА ИСХОДНИК, хотя утверждение о форме исходника — суррогат.
Предмет проверки ЕСТЬ правка исходника: ключ в YAML-блоке появляется только тем, что его туда
кто-то дописывает. Перечень при этом не переписывается сюда — обе стороны ВЫВОДЯТСЯ: ключи берутся
разбором тела `renderBuild()`, допустимые — импортом настоящего `_ALLOWED` и настоящего адаптера
`auth`. Спутник обязателен: ПОЛ на число найденных ключей, потому что разбор, переставший что-либо
находить, пройдёт идеально над пустым множеством.

Run: .venv/bin/python tests/test_export_channels_offline.py
"""
import io
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from brain import adapters                                            # noqa: E402
from brain.runconfig import _ALLOWED                                  # noqa: E402

FAILS = []


def check(name, cond, detail=""):
    if cond:
        print("  ok  ", name)
    else:
        FAILS.append(name)
        print("  FAIL", name, "\n       ", str(detail)[:400])


def hub():
    return io.open(os.path.join(ROOT, "docs", "index.html"), encoding="utf-8").read()


def render_build_body(page):
    """Тело renderBuild() от объявления до передачи собранного текста в узел — то есть ровно тот
    участок, который АВТОРИТ экспортируемый файл. Границы взяты по коду, а не по номерам строк:
    номера уезжают, и реестр этой волны ошибся ими четырежды."""
    i = page.index("function renderBuild()")
    j = page.index("ge('b-yaml').textContent", i)
    return page[i:j]


def exported_yaml_keys(page):
    """Ключи, которые сборщик кладёт в run.yaml. Верхние и вложенные (секция auth) различаются
    отступом в самом литерале, потому что различаются и правилами: верхние проверяет `_ALLOWED`,
    вложенные — `keys` выбранного адаптера."""
    body = render_build_body(page)
    top, nested = set(), set()
    for indent, key in re.findall(r"lines\.push\('( *)([a-z_]+):", body):
        (nested if indent else top).add(key)
    return top, nested


# ОБЪЯВЛЕННОЕ ИСКЛЮЧЕНИЕ, А НЕ МОЛЧАНИЕ. Форма скопирована с `componentsWithoutProbe`
# (cmd/control-api/readyz.go), где отсутствие декларации само по себе объявлено провалом: иначе у
# пропуска нет места, куда записать «почему», и гейту пришлось бы принимать молчание.
#
# Исключение САМОИСТЕКАЕТ: как только ключ появится у адаптера, проверка ниже потребует убрать его
# отсюда. Протухшее исключение — это тихо выключенная проверка, и оно здесь невозможно по устройству.
# ⚠ ЗДЕСЬ БЫЛО ОБЪЯВЛЕННОЕ ИСКЛЮЧЕНИЕ ДЛЯ `login_plan`, И ОНО САМОИСТЕКЛО, КАК И ЗАДУМАНО.
# Гейт нашёл ключ на первом же прогоне (W17, PR-7): экспорт писал его в секцию `auth`, а адаптер не
# принимал — ключ разделял судьбу тех пяти флагов, ради которых файл написан. Пропуск был ОБЪЯВЛЕН
# с причиной и с условием снятия: «как только у ключа появится потребитель, гейт потребует убрать
# запись». Потребитель появился (M9.1_CONTRACT §4.1), гейт потребовал — запись снята.
#
# Это и есть проверка на протухшее исключение в работе: она сработала не на чужой правке, а на той,
# ради которой заводилась.
PENDING_CONSUMER = {}


def test_the_yaml_builder_pushes_only_literal_keys():
    """ПОЧЕМУ ЭТА ПРОВЕРКА СУЩЕСТВУЕТ — она ДЕЛАЕТ РАЗБОР ВЫШЕ ПОЛНЫМ, и куплена мутацией, а не
    рассуждением. Первая редакция этого файла читала только литеральные `lines.push('key: …')`, и
    мутация, доставляющая те же пять полей ВЫЧИСЛЯЕМЫМ ключом (`lines.push(name+': '+…)` обходом
    RUN_FLAG), прошла её НАСКВОЗЬ: гейт напечатал ALL PASS над продуктом, который снова писал в файл
    ключи, молча выбрасываемые загрузчиком. Разностный гейт хаба ту же мутацию тоже пропустил — ему
    довольно, что экспорт сдвинулся, — и поймал из пяти полей ровно одно (heal_llm), и то по другому
    признаку.

    Лечение — не «разобрать вычисляемые ключи» (их в общем случае не разобрать), а ЗАПРЕТИТЬ форму,
    которой разбор не видит: пока каждый ключ в сборщике литерален, разбор выше видит ВСЁ, что
    сборщик пишет. Утверждение отрицательное и проверяет ровно свою слепую зону."""
    body = render_build_body(hub())
    computed = [m for m in re.findall(r"lines\.push\(([^'\n][^\n]{0,40})", body)]
    check("каждый ключ экспорта записан литералом, иначе разбор выше слеп", not computed,
          "вычисляемый ключ в сборщике YAML: %s — разбор ключей его не видит, и проверка "
          "«каждый верхний ключ читается загрузчиком» становится вакуумной" % computed[:3])


def auth_subkeys():
    adapters.load_from_env()
    return set(adapters.get(adapters.AUTH, adapters.DEFAULTS[adapters.AUTH]).keys)


def test_the_export_writes_no_key_the_loader_would_discard():
    """Дефект, который эта проверка обязана ловить: «починка» доставки через YAML-ключ вместо флага.
    Разностный гейт на такой правке остаётся зелёным — ему достаточно, что экспорт сдвинулся."""
    top, nested = exported_yaml_keys(hub())
    # `auth` — сама секция, её значение пустое; она есть в _ALLOWED и проверяется вместе с верхними.
    check("разбор нашёл ключи экспорта, а не пустое множество", len(top) >= 10,
          "найдено верхних ключей: %d — разбор renderBuild перестал совпадать, и проверка ниже "
          "проходит вакуумно" % len(top))
    unknown = sorted(k for k in top if k not in _ALLOWED)
    check("каждый верхний ключ экспорта читается загрузчиком", not unknown,
          "загрузчик молча выбросит %s: человек прочитает в файле выбор, которого прогон не сделает "
          "(_ALLOWED = %s)" % (unknown, sorted(_ALLOWED)))
    known = auth_subkeys()
    stray = sorted(k for k in nested if k not in known and k not in PENDING_CONSUMER)
    check("каждый вложенный ключ секции auth объявлен адаптером или объявлен исключением", not stray,
          "адаптер auth принимает %s, а экспорт пишет %s" % (sorted(known), stray))
    stale = sorted(k for k in PENDING_CONSUMER if k in known)
    check("объявленное исключение ещё нужно", not stale,
          "%s получил потребителя — снять запись из PENDING_CONSUMER, иначе она тихо выключает "
          "проверку для ключа, который она обязана покрывать" % stale)


def test_no_field_is_carried_by_both_channels_at_once():
    """Второй способ сделать экспорт лгущим — дать одному значению ОБА канала. Тогда у файла и у
    команды появляется по своему мнению о нём, и спор решается порядком, которого человек не видит.
    Утверждение выводится из обеих карт страницы, а не из списка имён."""
    page = hub()
    i = page.index("var RUN_FLAG = {")
    block = page[i:page.index("};", i)]
    flagged = set(re.findall(r"\n\s+([a-z_]+):\s*\{", block))
    check("карта argv-канала разобрана", len(flagged) >= 3,
          "в RUN_FLAG найдено %d записей — разбор отстал от формы объявления" % len(flagged))
    both = sorted(flagged & set(_ALLOWED))
    check("ни одно поле не едет двумя каналами сразу", not both,
          "%s объявлены флагом И читаются из run.yaml — два источника, спорящих об одном значении" % both)


def main():
    print("[HUB-EXPORT-DROPS-FIVE-RUN-FLAGS] каналы доставки экспорта")
    for fn in (
        test_the_yaml_builder_pushes_only_literal_keys,
        test_the_export_writes_no_key_the_loader_would_discard,
        test_no_field_is_carried_by_both_channels_at_once,
    ):
        fn()
    if FAILS:
        print("\nFAIL — %d check(s): %s" % (len(FAILS), ", ".join(FAILS)))
        return 1
    print("\nALL PASS")
    return 0


if __name__ == "__main__":
    sys.exit(main())
