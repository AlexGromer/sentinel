/**
 * ADR-142 — рекордер вкладки СПРАШИВАЕТСЯ, а не переустанавливается на каждую смену маршрута.
 *
 * ЧТО ЭТО ЗАКРЫВАЕТ. `chrome.tabs.onUpdated` поднимает `{status:'complete'}` не только на загрузку
 * документа, но и на `pushState`, `replaceState`, присвоение `location.hash` и `history.back` —
 * замерено на Chrome 151 и Chromium 150 (ADR-138 поправил на этом месте ЛОЖНЫЙ комментарий,
 * утверждавший обратное, но поведение осталось). Фильтр в `index.ts` проходит на всех четырёх, и на
 * всплеске из трёх `pushState` инъекция шла ТРИЖДЫ. Корректности это не ломало — обе защёлки
 * (`__sentinelRecorderInstalled`, `__sentinelRouteJournal`) держат, — но на SPA с частым
 * `replaceState` это сотни лишних `executeScript` на прогон, и каждый из них тащит два бандла.
 *
 * ПОЧЕМУ ПИНГ, А НЕ ФИЛЬТР ПО `url`. Отличить смену маршрута от загрузки документа по полям события
 * нельзя: `{status:'complete'}` НЕ несёт `url` вовсе, а событие с `url` приходит отдельно и раньше.
 * Единственный наблюдаемый факт, который отвечает на нужный вопрос, — жив ли content-script в этой
 * вкладке ПРЯМО СЕЙЧАС. Его и спрашиваем.
 *
 * ⚠ КАНАЛ ПИНГА УЖЕ СУЩЕСТВОВАЛ, и новой вербы заводить не пришлось: `chrome.tabs.sendMessage`
 * РЕДЖЕКТИТСЯ, когда в вкладке некому принять сообщение, и `tellTab` это уже ловил — с
 * комментарием «no recorder in that tab yet». То есть отличие «жив / мёртв» было наблюдаемо всё
 * это время; недоставало только того, чтобы кто-то на него посмотрел ДО инъекции, а не после.
 *
 * ⚠ СООБЩЕНИЕ-ПИНГ ИДЕМПОТЕНТНО НАМЕРЕННО. Это тот же `record-control`, который и так посылался
 * ПОСЛЕ каждой инъекции, поэтому успешный пинг не просто отвечает на вопрос — он доставляет ровно
 * то, ради чего инъекция затевалась. Пинг «ничего не делающим» сообщением потребовал бы новой
 * формы строки в протоколе и второго обработчика в content — двух механизмов вместо нуля.
 *
 * ПОЧЕМУ ОТДЕЛЬНЫЙ ФАЙЛ. `index.ts` при импорте регистрирует слушателей на `chrome.*`, поэтому в
 * jsdom его не импортировать. Решение вынесено сюда чистой функцией над двумя зависимостями —
 * и проверяется без `chrome` вообще (`ensure-recorder.test.ts`).
 */

/** То, что `ensureRecorder` умеет делать с вкладкой. Обе операции отвергаются, когда вкладки нет. */
export type EnsureDeps = {
  /** Сказать content-script'у вкладки, что запись идёт. ОТВЕРГАЕТСЯ, если принять некому. */
  ping: (tabId: number) => Promise<unknown>;
  /** Поставить оба бандла (ISOLATED + MAIN). Дорого: два `executeScript`. */
  inject: (tabId: number) => Promise<void>;
};

/** Что произошло — возвращается ради наблюдаемости и ради утверждений гейта. */
export type EnsureOutcome = 'alive' | 'injected' | 'gone';

/**
 * Убедиться, что во вкладке есть живой рекордер, НЕ переустанавливая его без нужды.
 *
 * Порядок вопросов — часть конструкции: сначала «он там есть?», и только если нет — «поставить».
 * Обратный порядок и был дефектом: он ставил, а потом сообщал.
 */
export async function ensureRecorder(tabId: number, deps: EnsureDeps): Promise<EnsureOutcome> {
  try {
    await deps.ping(tabId);
    // Ответили — значит content-script жив, документ не заменялся, и это была смена МАРШРУТА.
    // Сообщение доставлено, ставить нечего.
    return 'alive';
  } catch {
    // Принять некому: документ действительно заменён (полная загрузка) — ради этого случая
    // переинъекция и писалась.
  }
  try {
    await deps.inject(tabId);
  } catch {
    // Вкладка закрыта или не скриптуема. Не наша ошибка и не повод шуметь: `recorder-ready`
    // пересинхронизирует, если вкладка ещё жива.
    return 'gone';
  }
  // Свежепоставленному рекордеру состояние надо сообщить — до инъекции его слушать было некому.
  await deps.ping(tabId).catch(() => {});
  return 'injected';
}
