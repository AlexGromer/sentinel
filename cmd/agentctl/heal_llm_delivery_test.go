package main

// HEAL_LLM доезжает до мозга — утверждается НАБЛЮДЕНИЕМ за окружением, которое мозг реально получил.
//
// ЧТО БЫЛО ЗАМЕРЕНО. ADR-165 чинил ровно эту доставку: `HEAL_LLM` стоял в схеме, интерфейс его
// сохранял и подтверждал, а до прогона значение не доезжало ни разу — имени не было в аллоулисте
// (`filteredEnv`), и вдобавок безусловный run-var затирал унаследованное нулём. Стерегущая эту
// починку проверка — `test_every_published_setting_actually_reaches_a_run` — объявляла в своей
// строке KILLS «возврат безусловного run-var для HEAL_LLM», но выводила «безусловность» РЕГУЛЯРКОЙ
// ПО ОДНОМУ ЛИТЕРАЛУ `extra := []string{…}`, тогда как запись HEAL_LLM живёт ЗА ним:
//
//	if setFlags["heal-llm"] {
//	    extra = append(extra, "HEAL_LLM="+boolEnv(*healLLM))
//	}
//
// Снять `if`, оставив `append`, — и множество `unconditional` не изменится, `deliverable` ответит
// «точное имя в аллоулисте», гейт останется зелёным над восстановленным дефектом. Замерено: до
// появления этого файла ни один тест во всём дереве не утверждал, что значение HEAL_LLM доезжает
// куда-либо; единственное упоминание в Go-тестах — `config_projection_test.go`, и оно про то, что
// control-api выдаёт флаг `--heal-llm`, а не про то, что мозг что-то получает.
//
// ПОЧЕМУ ТЕСТ ВЫГЛЯДИТ ТАК. Утверждение о ФОРМЕ ИСХОДНИКА — суррогат: мутация проходит сквозь
// заявление о тексте. Здесь гоняется настоящий `cmdRun` с подставным мозгом, который записывает
// доставшееся ему окружение, и утверждаются ОБЕ половины дефекта разом — и аллоулист, и условность
// записи, — одним наблюдением, которое переживает любой рефакторинг того и другого.
//
// ⚠ ОБОБЩАТЬ НЕЛЬЗЯ. Правило «ни один run-var не должен быть безусловным» сломало бы намеренный
// контракт `SENTINEL_OBSERVE` (observe_flag_test.go): там безусловная перезапись закреплена тестом
// в обе стороны и объяснена рядом с кодом. Поэтому утверждение здесь — поимённое.

import (
	"runtime"
	"strings"
	"testing"
)

func TestTheSavedHealLLMReachesTheBrain(t *testing.T) {
	if runtime.GOOS == "windows" {
		t.Skip("the brain stub is a /bin/sh script")
	}
	const target = "file:///dev/null"

	// 1. НИЧЕГО НЕ ВЫБРАНО НА ПРОГОН — сохранённый слой обязан выжить. Это и есть починка ADR-165:
	// имя проходит аллоулист, а run-var дописывается ТОЛЬКО когда флаг реально передан. Верните
	// запись под безусловный `append` — и здесь появится HEAL_LLM=0 поверх унаследованной единицы.
	t.Setenv("HEAL_LLM", "1")
	got := brainEnvAfterRun(t, []string{"--target", target})
	if !strings.Contains(got, "HEAL_LLM=1") {
		t.Errorf("сохранённый HEAL_LLM=1 не доехал до мозга: человек включил самопочинку LLM, "+
			"получил подтверждение, и прогон пошёл без неё.\nenv:\n%s", got)
	}
	if strings.Contains(got, "HEAL_LLM=0") {
		t.Errorf("унаследованное значение затёрто нулём — это ровно тот дефект, который закрывал "+
			"ADR-165: run-var дописывается ПОСЛЕ окружения, и os/exec берёт последнее.\nenv:\n%s", got)
	}

	// 2. ВЫБРАНО ЯВНОЕ «НЕТ» — оно обязано победить сохранённое. Без этой половины «доставка
	// работает» удовлетворялась бы тем, что окружение случайно несёт нужное значение, а флаг не
	// делает ничего; и отменить сохранённую единицу на один прогон было бы нечем.
	t.Setenv("HEAL_LLM", "1")
	got = brainEnvAfterRun(t, []string{"--target", target, "--heal-llm=false"})
	if !strings.Contains(got, "HEAL_LLM=0") {
		t.Errorf("явное --heal-llm=false не перебило сохранённое HEAL_LLM=1: выключить самопочинку "+
			"на один прогон нечем.\nenv:\n%s", got)
	}
}
