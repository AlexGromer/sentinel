package main

// Удаление, которое не умеет отказать, — это удаление, о котором нельзя узнать, что оно не случилось.
//
// ЧТО ЗАМЕРЕНО. Четыре клиентских метода хранилища — `deleteUser`, `deleteScenario`, `deleteTest`,
// `deleteChat` — НИЧЕГО НЕ ВОЗВРАЩАЮТ: ошибку gRPC/БД они печатают в stderr control-api и глотают.
// Обработчик поверх них отвечает «deleted»/«removed» БЕЗУСЛОВНО. Человек нажимает «удалить», видит
// подтверждение, объект остаётся на месте, и следующее, что он узнает, — что «удалённый» сценарий
// снова в списке.
//
// ⚠ ЗАПИСЬ РЕЕСТРА ПЕРЕОЦЕНИЛА ДЕФЕКТ НА ОДНУ ПОЛОВИНУ, и это замерено. Она винила ещё и случай
// `s.store == nil` — «попытки не было ни одной». Но там, где хранилища нет, объектов нет ВООБЩЕ:
// список отдаёт пусто, `GET` по адресу отдаёт 404, и удаление заведомо несуществующего успешно по
// той же причине, что удаление отсутствующей строки. Это закреплённый контракт вехи
// (M14_CONTRACT.md §3, `TestScenariosTestsChatsFailOpenNoStore`), и ломать его было бы регрессом,
// а не починкой. Настоящий дефект — ОТКАЗ хранилища, которое есть.
//
// Хуже всего у аккаунта: журнал пишет `service.account_deleted` на уровне warn ДО вызова, поэтому
// служебная запись утверждает удаление, которого могло не быть. Это ровно тот класс, ради которого
// заведён журнал: «кто что удалил и когда» — и он отвечает на это неправдой.
//
// ⚠ ДОВОД ПРО ИДЕМПОТЕНТНОСТЬ НЕ ЗАЩИЩАЕТ ЭТОТ КОД. Комментарий у обработчика говорит:
// «idempotent: missing id (or no store) is still success». Идемпотентность обеспечивает САМ SQL —
// `DELETE ... WHERE id=?` по отсутствующей строке успешен, и гейтвей отвечает OK. Отказ ТРАНСПОРТА
// или БД — не идемпотентность, а несделанная работа, и складывать их в один ответ значит отвечать
// «готово» на «не смог».
//
// ОБРАЗЕЦ ЛЕЧЕНИЯ УЖЕ БЫЛ НАПИСАН РЯДОМ: `deleteConfig` (store.go) возвращает `error` — единственный
// из пяти. Правка приводит остальные четыре к нему, а не изобретает форму.
//
// ПОЧЕМУ ТЕСТ ВЫГЛЯДИТ ТАК. Утверждается КОД ОТВЕТА при ЗАВЕДОМО недоступном хранилище (`deadStore`:
// сокет, на котором никто не слушает — так выглядит гейтвей, умерший после старта). Наблюдение
// независимое: недоступность создаётся транспортом, а не подменой нашей же функции, поэтому
// утверждение не повторяет формулу реализации.

import (
	"net/http"
	"strings"
	"testing"

	storepb "github.com/AlexGromer/sentinel/internal/store/pb"
)

// deleteRoutes — все четыре удаления, которые глотали отказ. Перечень ЗДЕСЬ, а не выведенный: это
// закрытый список записей реестра, и его рост должен быть осознанным.
func deleteRoutes() []struct{ name, path string } {
	return []struct{ name, path string }{
		{"scenario", "/v1/scenarios/some-id"},
		{"test", "/v1/tests/some-id"},
		{"chat", "/v1/chats/some-id"},
	}
}

func TestADeletionThatCouldNotHappenDoesNotAnswerDeleted(t *testing.T) {
	for _, rt := range deleteRoutes() {
		t.Run(rt.name, func(t *testing.T) {
			s := newTestServer()
			s.store = deadStore(t) // гейтвей, умерший после старта: каждый вызов отказывает

			rec, body := doJSON(t, s, http.MethodDelete, rt.path, nil, "secret-tok")
			if rec.Code == http.StatusOK {
				t.Fatalf("%s: хранилище недоступно, а ответ «%v» — человек увидел подтверждение удаления, "+
					"которого не было, и узнает об этом, когда объект снова окажется в списке", rt.path, body)
			}
			if rec.Code != http.StatusBadGateway && rec.Code != http.StatusServiceUnavailable {
				t.Errorf("%s: код %d не говорит, что виновато ХРАНИЛИЩЕ, а не запрос: %v", rt.path, rec.Code, body)
			}
			if msg, _ := body["error"].(string); strings.TrimSpace(msg) == "" {
				t.Errorf("%s: отказ без текста — человеку нечего прочитать: %v", rt.path, body)
			}
		})
	}
}

// Аккаунт стоит отдельно: у него есть служебная запись, и она не имеет права утверждать удаление,
// которого не было. Запись обязана идти ПОСЛЕ успеха, а не до попытки.
func TestADeletedAccountIsNotJournalledUntilItIsActuallyGone(t *testing.T) {
	s := journalServer(t, "info")
	s.store = deadStore(t)

	rec, body := doJSON(t, s, http.MethodDelete, "/v1/users/u-1", nil, "secret-tok")
	if rec.Code == http.StatusOK {
		t.Fatalf("хранилище недоступно, а ответ «%v»: токен аккаунта уже сброшен, сам аккаунт жив, "+
			"и развёртывание считает его удалённым", body)
	}
	for _, r := range readJournal(t, s.repo) {
		if r.Code == "service.account_deleted" {
			t.Errorf("журнал утверждает удаление аккаунта, которого не произошло: запись сделана ДО " +
				"вызова хранилища, а «кто что удалил» — ровно тот вопрос, ради которого журнал существует")
		}
	}
}

// Обратная сторона, без которой «починка» удовлетворялась бы отказом ВСЕГДА: отсутствующий объект —
// это по-прежнему успех. Идемпотентность обеспечивает SQL, и её терять нельзя.
func TestDeletingSomethingAbsentIsStillSuccess(t *testing.T) {
	s, _, _, _ := storeBackedServer(t)
	for _, rt := range deleteRoutes() {
		rec, body := doJSON(t, s, http.MethodDelete, rt.path, nil, "secret-tok")
		if rec.Code != http.StatusOK {
			t.Errorf("%s: удаление отсутствующего объекта отказало (%d, %v) — идемпотентность потеряна, "+
				"и повторное удаление стало ошибкой", rt.path, rec.Code, body)
		}
	}
	_ = storepb.UserRef{}
}
