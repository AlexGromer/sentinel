package main

// [CFG-GROUP-LABELS-STOPPED-COVERING] — у каждой группы настроек есть человеческое имя на обоих
// языках, и у каждого имени есть группа.
//
// ЧТО БЫЛО ЗАМЕРЕНО. `settingsSchema` объявляет у каждой записи ГРУППУ и не объявляет, как группа
// называется по-человечески. Имя приходилось дублировать руками, и копий было ДВЕ — `CFG_GROUP_LABELS`
// в хабе и `SETTING_GROUPS` в мастере. ADR-165 вырастил схему с 16 записей и 4 групп до 44 и 13; обе
// копии остались на четырёх, и ни одна проверка этого не увидела: 9 заголовков из 13 приезжали в хаб
// сырым латинским ключом ОДИНАКОВО в обе языковые колонки (прямое нарушение ADR-085), а в хабе жила
// метка `logging`, не принадлежащая НИ ОДНОЙ группе.
//
// ⚠ И ЦЕНА БЫЛА НЕ КОСМЕТИЧЕСКОЙ, хотя запись реестра оценила её как P3. Мастер рисовал контролы
// только для групп своей копии — 23 из 44, — `buildConfigDoc` собирает лишь отрисованное, а PUT
// замещает секцию целиком. Одно сохранение из мастера уничтожало 21 сохранённое значение МОЛЧА.
//
// СВЕРКА В ОБЕ СТОРОНЫ — не симметрия ради симметрии: одна сторона ловит отставшую метку, другая —
// мёртвую. Требование КИРИЛЛИЦЫ в `ru` закрывает третий способ пройти вакуумно: «покрытие»
// удовлетворялось бы записью `llm: {ru:"llm", en:"llm"}`, то есть тем самым дефектом под видом
// починки.

import (
	"testing"
	"unicode"
)

func TestEverySettingGroupHasBilingualLabel(t *testing.T) {
	groups := map[string]bool{}
	for name, d := range settingsSchema {
		m, ok := d.(map[string]any)
		if !ok {
			t.Fatalf("дескриптор %q не отображение — обход ниже сравнивает не то", name)
		}
		g, _ := m["group"].(string)
		if g == "" {
			t.Errorf("настройка %q не объявляет группу — её негде показать и нечем назвать", name)
			continue
		}
		groups[g] = true
	}
	// Полы: сравнение двух пустых множеств сходится идеально.
	if len(settingsSchema) < 30 {
		t.Fatalf("в схеме %d настроек — разбор отстал, и всё ниже вакуумно", len(settingsSchema))
	}
	if len(groups) < 5 {
		t.Fatalf("выведено %d групп — обход перестал что-либо находить", len(groups))
	}

	for g := range groups {
		lab, ok := settingGroups[g]
		if !ok {
			t.Errorf("группа %q не имеет человеческого имени — заголовок приедет сырым ключом "+
				"ОДИНАКОВО в обе языковые колонки (ADR-085)", g)
			continue
		}
		ru, _ := lab["ru"].(string)
		en, _ := lab["en"].(string)
		if ru == "" || en == "" {
			t.Errorf("группа %q названа не на обоих языках: ru=%q en=%q", g, ru, en)
		}
		// Кириллица, потому что иначе «покрытие» удовлетворяется записью `{ru:"llm", en:"llm"}` —
		// дефектом под видом починки.
		cyr := false
		for _, r := range ru {
			if unicode.Is(unicode.Cyrillic, r) {
				cyr = true
				break
			}
		}
		if !cyr {
			t.Errorf("русское имя группы %q не содержит кириллицы (%q) — это латинский ключ под видом перевода", g, ru)
		}
		if _, has := lab["order"]; !has {
			t.Errorf("группа %q не объявляет порядок — разделы поехали бы в порядке обхода map, "+
				"который в Go не определён", g)
		}
	}
	// Обратная сторона: метка без группы — мёртвый перевод, и именно такой (`logging`) жил в хабе.
	for g := range settingGroups {
		if !groups[g] {
			t.Errorf("имя объявлено для группы %q, которой нет ни у одной настройки — мёртвая метка", g)
		}
	}
}
