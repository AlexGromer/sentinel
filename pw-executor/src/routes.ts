/**
 * pw-executor — журнал смен маршрута, который ведёт САМА СТРАНИЦА (W8 PR-2, ADR-135).
 *
 * WHAT WAS MEASURED before this file existed. Фронтир обхода строился из одного источника —
 * `a[href]` через `browser.links`. Маршрут, до которого ведёт только `<button>` + `history.pushState`,
 * не попадал в него никогда. ADR-132 научил обход РАЗЛИЧАТЬ такие маршруты (фрагмент участвует в
 * идентичности страницы), ADR-134 — надёжно ЗАМЕЧАТЬ, что клик оказался навигацией. Оставалось
 * третье: узнать о маршруте, который приложение открыло и с которого ушло раньше, чем снаружи
 * успели прочитать адрес. Снимок `page.url()` видит ПОСЛЕДНЕЕ состояние адресной строки; цепочка
 * `push A → push B` в одном такте оставляет от A ровно ничего.
 *
 * ⚠ УСТАНАВЛИВАЕТСЯ ЧЕРЕЗ `addInitScript`, А НЕ `evaluate`, и причина та же, что записана в
 * `decorate.ts:24-28`: одноразовый `evaluate` стирается первой же навигацией, и режим работал бы
 * ровно до тех пор, пока прогон куда-нибудь не пошёл. Для украшения это означало бы пропавший
 * курсор; здесь — молчаливо пустой журнал, то есть находку, о которой никто не узнает.
 *
 * ⚠ И ставится БЕЗУСЛОВНО, в отличие от украшений. `installDecorations` стоит под `if (decorate)`
 * (`server.ts:587`), потому что украшение — это режим для человека. Журнал маршрутов — не режим:
 * от него зависит, что обход вообще найдёт. Скрипт, поставленный под флагом, дал бы продукт, у
 * которого полнота обхода зависит от того, смотрит ли кто-то на экран.
 *
 * ⚠ НИ ОДНОЙ СТРОКИ В DOM. Украшение рисует и потому обязано убирать за собой вокруг чистых
 * кадров (`withCleanFrame`); журнал не рисует ничего и в кадр не попадает по построению. Это не
 * экономия, а требование: перцепция и голдены не должны видеть разницы между страницей с журналом
 * и без него.
 */
import type { BrowserContext, Page } from 'playwright';

/**
 * Потолок журнала. Переполнение НЕ вытесняет накопленное: запись прекращается, а отброшенное
 * считается отдельно.
 *
 * ⚠ ВЫТЕСНЕНИЕ СТАРОГО БЫЛО БЫ ХУЖЕ, и это выбор, а не умолчание кольцевого буфера. Ценность
 * записи для фронтира — в том, что адрес встретился ВПЕРВЫЕ; поздние записи почти всегда повторы
 * уже увиденного. Приложение, дёргающее `replaceState` в цикле (частая идиома синхронизации
 * фильтра с адресом), при вытеснении вымыло бы из журнала ровно уникальные ранние маршруты и
 * оставило бы пятьсот копий одного. Поэтому переполнение теряет ХВОСТ, а не голову.
 *
 * Экспортируется, чтобы гейт мерил МЕХАНИЗМ (сколько ни толкай — журнал ограничен, а разница
 * названа в `dropped`), а не запомненное число.
 */
export const ROUTE_JOURNAL_MAX = 500;

/** Один глобал, которым страничная половина отвечает Node. Адресуется гейтом по имени. */
export const ROUTE_API = '__sentinelRoutes';

/**
 * Как адрес сменился. ТРИ значения, и третьего — `hash` — здесь НЕТ по замеру, а не по забывчивости.
 *
 * ⚠ ЗАМЕРЕНО В ЖИВОМ CHROMIUM (2026-08-24), три случая из трёх: присвоение `location.hash`, клик по
 * `<a href="#/x">` и `history.back()` поднимают `popstate` И `hashchange`, причём `popstate` ВСЕГДА
 * первым. Отдельный слушатель `hashchange` поэтому не может выиграть отсечку повтора ни разу, и
 * значение `hash` в журнале не появилось бы никогда — то есть было бы мёртвой альтернативой,
 * которую читатель артефакта принял бы за нечто, что бывает.
 *
 * Слушатель убран, а замер положен в гейт: `routes.test.ts` утверждает, что клик по якорю-фрагменту
 * даёт запись. Если движок когда-нибудь перестанет поднимать `popstate` на фрагмент, красным станет
 * тест, а не тишина в журнале.
 */
export type RouteHow = 'push' | 'replace' | 'pop';

export interface RouteRecord {
  url: string;
  ts: number;
  how: RouteHow;
}

/** Что отдаёт верба. `journal: false` — единственный ответ, который человек обязан увидеть в логе:
 *  он означает, что init-скрипт на этом документе не отработал, то есть инъекция потеряна. */
export interface RouteTake {
  routes: RouteRecord[];
  dropped: number;
  journal: boolean;
}

/**
 * Страничная половина. Строкой, потому что это то, что принимает `addInitScript({content})` —
 * та же форма и по той же причине, что `DECOR_INIT_SCRIPT` (`decorate.ts:88`).
 *
 * Перехватываются ТРИ механизма, и этого хватает на все известные способы сменить адрес без
 * перезагрузки документа — что замерено, а не предположено (см. `RouteHow`):
 *   `history.pushState`    — новая запись в истории. Событий не поднимает вовсе, поэтому увидеть
 *                            её можно ТОЛЬКО обёрткой;
 *   `history.replaceState` — подмена текущей. Тоже молчит, и вдобавок не оставляет следа в истории:
 *                            именно ею роутеры делают редиректы, и именно она невидима снаружи
 *                            полностью;
 *   `popstate`             — назад/вперёд, присвоение `location.hash` и клик по якорю-фрагменту.
 *                            Все три случая замерены: Chromium поднимает `popstate` на каждый.
 *
 * ⚠ ЗАПИСЫВАЕТСЯ `location.href` ПОСЛЕ вызова, а не аргумент. Аргумент бывает относительным
 * (`'orders'`, `'./x'`, `'#/y'`), и разрешать его пришлось бы нам — то есть повторить работу
 * браузера и разойтись с ним на первом же краю. Адрес, который получился, знает только адресная
 * строка.
 *
 * ⚠ ПОДРЯД ИДУЩИЙ ПОВТОР НЕ ЗАПИСЫВАЕТСЯ, и это про ПОТОЛОК, а не про экономию. Синхронизация
 * состояния экрана с адресом через `replaceState` на каждый чих (фильтр, сортировка, скролл) —
 * массовая идиома; без отсечки такое приложение за десяток шагов выбирает потолок журнала
 * копиями одного адреса и вытесняет наружу, в `dropped`, всё, что мы ради этого журнала и заводили.
 * Сравнение с ПОСЛЕДНЕЙ записью, а не со всем журналом — чтобы `A → B → A` осталось тремя записями
 * (это разные моменты, и обход обязан видеть возврат), и чтобы стоимость не росла квадратично.
 */
export const ROUTE_INIT_SCRIPT = `(function () {
  if (window.${ROUTE_API}) return;
  var MAX = ${ROUTE_JOURNAL_MAX};
  var log = [];
  var dropped = 0;
  var last = null;

  function note(how) {
    var href;
    try { href = String(window.location.href); } catch (e) { return; }
    if (href === last) return;
    last = href;
    if (log.length >= MAX) { dropped += 1; return; }
    log.push({ url: href, ts: Date.now(), how: how });
  }

  function wrap(name, how) {
    var orig = window.history[name];
    if (typeof orig !== 'function') return;
    window.history[name] = function () {
      // Оригинал зовётся ПЕРВЫМ и его результат возвращается как есть: обёртка обязана быть
      // прозрачной для приложения. Если бы она глотала исключение SecurityError (а pushState его
      // бросает — например, на смену пути в схеме без происхождения), роутер приложения перестал
      // бы получать отказ, на который он рассчитывает, и пошёл бы по другой ветке из-за нас.
      var r = orig.apply(window.history, arguments);
      try { note(how); } catch (e) { /* журнал не имеет права ломать навигацию */ }
      return r;
    };
  }

  wrap('pushState', 'push');
  wrap('replaceState', 'replace');
  window.addEventListener('popstate', function () { try { note('pop'); } catch (e) {} });

  window.${ROUTE_API} = {
    take: function () {
      var out = { routes: log, dropped: dropped };
      // Отдать И ОЧИСТИТЬ — одним движением. Журнал, который читают и не чистят, отдаёт на каждом
      // шаге всё, что было с начала прогона: ворота фронтира тихо отсеют это по ADMIT_KNOWN, и
      // утверждение «фронтир вырос» останется верным, а стоимость будет расти квадратично, ничем
      // себя не выдавая. Переменная last НЕ сбрасывается: она про соседство записей во времени, а не про
      // содержимое журнала.
      log = [];
      dropped = 0;
      return out;
    },
  };
})();`;

/**
 * Регистрация на КОНТЕКСТЕ — переживает навигацию и покрывает попапы и новые вкладки,
 * как `installDecorations` (`decorate.ts:213-222`).
 *
 * ⚠ И ОДИН ПРОХОД ПО УЖЕ ОТКРЫТЫМ СТРАНИЦАМ. `addInitScript` действует только на БУДУЩИЕ
 * документы — это его контракт, а не недосмотр. В режиме launch это безразлично: страница прогона
 * создаётся после установки. В CDP-attach контекст принадлежит чужому браузеру, и там УЖЕ открыт
 * документ, на котором скрипт не отработает до первой навигации, — то есть режим наблюдения за
 * живой сессией работал бы ровно наполовину и молча. Одноразовый `evaluate` тем же исходником
 * закрывает эту дыру; повторной установки он не делает, потому что первый оператор скрипта —
 * `if (window.${ROUTE_API}) return`.
 */
export async function installRouteJournal(context: BrowserContext): Promise<void> {
  await context.addInitScript({ content: ROUTE_INIT_SCRIPT });
  for (const p of context.pages()) {
    await p.evaluate(ROUTE_INIT_SCRIPT).catch(() => {
      /* Страница может быть about:blank, закрываться или принадлежать чужому origin с CSP.
         Это не отказ установки: будущие документы её всё равно получат из addInitScript. */
    });
  }
}

/**
 * Снять журнал с ВЕРХНЕГО документа и очистить его.
 *
 * ⚠ ФРЕЙМЫ НЕ ОБХОДЯТСЯ, и это отличие от `browser.links`/`browser.interactives` — намеренное, с
 * причиной. Те два отвечают на вопрос «что есть на этом сайте»: ссылка внутри фрейма — это правда
 * место, куда можно пойти. Журнал отвечает на другой вопрос — «какой адрес был у ЭТОЙ страницы»;
 * маршрут, который роутер фрейма записал в адрес ФРЕЙМА, адресом страницы не является, и положить
 * его во фронтир значило бы предложить обходу навигацию верхнего документа туда, где живёт чужой
 * документ.
 */
export async function takeRoutes(page: Page): Promise<RouteTake> {
  const raw = await page.evaluate((api) => {
    const j = (window as unknown as Record<string, { take(): { routes: unknown[]; dropped: number } }>)[api];
    if (!j) return null;
    return j.take();
  }, ROUTE_API);
  if (!raw) return { routes: [], dropped: 0, journal: false };
  return { routes: raw.routes as RouteRecord[], dropped: raw.dropped, journal: true };
}
